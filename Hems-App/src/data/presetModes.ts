// Mod ID'ye göre mod bul
export const getModeById = (id: string): PresetMode | undefined => {
  return PRESET_MODES.find((mode) => mode.id === id);
};

// Ön tanımlı modları getir (custom hariç)
export const getPresetModes = (): PresetMode[] => {
  return PRESET_MODES.filter((mode) => !mode.isCustom);
};

// Custom mod al
export const getCustomMode = (): PresetMode | undefined => {
  return PRESET_MODES.find((mode) => mode.isCustom);
};

// Varsayılan mod (Dengeli Hibrit)
export const DEFAULT_MODE_ID = 'mode_8';

// Mod numarası al (1-8 veya "Özel")
export const getModeNumber = (id: string): string => {
  if (id === 'custom') return 'Özel';
  const match = id.match(/mode_(\d+)/);
  return match ? match[1] : '';
};
